begin;

create table if not exists public.link_pages (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9][a-z0-9-]{0,49}$'),
  title text not null check (char_length(trim(title)) between 1 and 80),
  bio text not null default '' check (char_length(bio) <= 240),
  avatar_url text,
  verified boolean not null default false,
  online boolean not null default true,
  is_active boolean not null default true,
  theme jsonb not null default '{"accent":"#735cf0","background":"#f8f7ff","card":"#ffffff","text":"#24233a"}'::jsonb,
  links jsonb not null default '[]'::jsonb,
  views bigint not null default 0,
  unique_visitors bigint not null default 0,
  clicks bigint not null default 0,
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(workspace_id, slug)
);
create index if not exists link_pages_slug_idx on public.link_pages(slug);
alter table public.link_pages enable row level security;
grant select, insert, update, delete on public.link_pages to authenticated;
create policy link_pages_read_member on public.link_pages for select to authenticated using (private.has_workspace_role(workspace_id, array['owner','admin','manager','va']));
create policy link_pages_insert_manager on public.link_pages for insert to authenticated with check (private.has_workspace_permission(workspace_id, 'manage_content'));
create policy link_pages_update_manager on public.link_pages for update to authenticated using (private.has_workspace_permission(workspace_id, 'manage_content')) with check (private.has_workspace_permission(workspace_id, 'manage_content'));
create policy link_pages_delete_admin on public.link_pages for delete to authenticated using (private.has_workspace_role(workspace_id, array['owner','admin']));
create trigger link_pages_set_updated_at before update on public.link_pages for each row execute function private.workspace_updated_at();

create or replace function public.trafficflow_get_public_link_page(p_slug text)
returns table(id uuid, workspace_id uuid, slug text, title text, bio text, avatar_url text, verified boolean, online boolean, is_active boolean, theme jsonb, links jsonb, views bigint, unique_visitors bigint, clicks bigint, created_at timestamptz)
language plpgsql security definer set search_path = '' as $$
begin
  return query select p.id,p.workspace_id,p.slug,p.title,p.bio,p.avatar_url,p.verified,p.online,p.is_active,p.theme,p.links,p.views,p.unique_visitors,p.clicks,p.created_at from public.link_pages p where p.slug=lower(trim(p_slug)) and p.is_active=true limit 1;
end;
$$;
revoke all on function public.trafficflow_get_public_link_page(text) from public, authenticated;
grant execute on function public.trafficflow_get_public_link_page(text) to anon, authenticated;

create table if not exists public.link_page_events (
  id bigint generated by default as identity primary key,
  page_id uuid not null references public.link_pages(id) on delete cascade,
  event_type text not null check (event_type in ('view','click')),
  link_id text,
  visitor_id text,
  created_at timestamptz not null default now()
);
create index if not exists link_page_events_page_idx on public.link_page_events(page_id, created_at desc);
alter table public.link_page_events enable row level security;
revoke all on public.link_page_events from anon, authenticated;

create or replace function public.trafficflow_track_link_page_event(p_page_id uuid, p_event_type text, p_link_id text default null, p_visitor_id text default null)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if p_event_type not in ('view','click') then raise exception 'invalid_link_page_event'; end if;
  insert into public.link_page_events(page_id,event_type,link_id,visitor_id) values(p_page_id,p_event_type,p_link_id,nullif(left(coalesce(p_visitor_id,''),120),''));
  if p_event_type = 'view' then
    update public.link_pages set views=views+1, unique_visitors=unique_visitors + case when p_visitor_id is not null and not exists(select 1 from public.link_page_events e where e.page_id=p_page_id and e.event_type='view' and e.visitor_id=p_visitor_id and e.id <> (select max(id) from public.link_page_events where page_id=p_page_id)) then 1 else 0 end where id=p_page_id and is_active=true;
  else update public.link_pages set clicks=clicks+1 where id=p_page_id and is_active=true; end if;
end;
$$;
revoke all on function public.trafficflow_track_link_page_event(uuid,text,text,text) from public, authenticated;
grant execute on function public.trafficflow_track_link_page_event(uuid,text,text,text) to anon, authenticated;

commit;
