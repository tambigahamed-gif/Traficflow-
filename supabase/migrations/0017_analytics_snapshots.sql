-- TrafficFlow 0017 — snapshots Analytics fournisseurs.
-- Données réelles uniquement : aucune ligne ne doit être créée sans réponse fournisseur.

create table if not exists public.analytics_snapshots (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  social_account_id integer not null references public.social_accounts(id) on delete cascade,
  platform text not null,
  provider_object_id text not null,
  metric_date date not null,
  metrics jsonb not null default '{}'::jsonb,
  source text not null,
  collected_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (social_account_id, provider_object_id, metric_date, source)
);

create index if not exists analytics_snapshots_workspace_date_idx
  on public.analytics_snapshots(workspace_id, metric_date desc);
create index if not exists analytics_snapshots_account_date_idx
  on public.analytics_snapshots(social_account_id, metric_date desc);

alter table public.analytics_snapshots enable row level security;
revoke all on public.analytics_snapshots from anon;
grant select on public.analytics_snapshots to authenticated;
grant all on public.analytics_snapshots to service_role;
create policy analytics_snapshots_read on public.analytics_snapshots
  for select to authenticated using (private.has_workspace_role(workspace_id, null));
