create or replace function private.has_workspace_role(p_workspace_id uuid, p_roles text[] default null)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = p_workspace_id
      and wm.user_id = (select auth.uid())
      and wm.status = 'active'
      and (p_roles is null or wm.role = any(p_roles))
  );
$$;

create or replace function private.has_workspace_permission(p_workspace_id uuid, p_permission text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = p_workspace_id
      and wm.user_id = (select auth.uid())
      and wm.status = 'active'
      and case wm.role
        when 'owner' then true
        when 'admin' then true
        when 'manager' then p_permission = any(array['view_analytics','view_content','create_content','edit_content','schedule','view_interactions','use_ai','manage_social_accounts','manage_tasks'])
        when 'va' then coalesce((wm.permissions ->> p_permission)::boolean, false)
        else false
      end
  );
$$;

