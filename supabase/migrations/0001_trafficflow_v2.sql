create or replace function private.can_access_account(p_workspace_id uuid, p_social_account_id integer, p_permission text default 'view_content')
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = p_workspace_id
      and wm.user_id = (select auth.uid())
      and wm.status = 'active'
      and (
        wm.role in ('owner','admin')
        or (
          wm.role in ('manager','va')
          and exists (
            select 1 from public.account_assignments aa
            where aa.workspace_id = p_workspace_id
              and aa.social_account_id = p_social_account_id
              and aa.user_id = (select auth.uid())
              and case wm.role
                when 'manager' then p_permission = any(array['view_content','view_analytics','create_content','edit_content','schedule','view_interactions','use_ai','manage_social_accounts','manage_tasks'])
                when 'va' then coalesce((aa.permissions ->> p_permission)::boolean, false)
                else false
              end
          )
        )
      )
  );
$$;

