create or replace function private.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  new_workspace_id uuid;
  display_name text;
begin
  display_name := coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), nullif(split_part(coalesce(new.email, ''), '@', 1), ''), 'Mon espace');
  insert into public.workspaces(name, owner_id) values (left(display_name || ' · Studio', 100), new.id) returning id into new_workspace_id;
  insert into public.workspace_members(workspace_id, user_id, role, status) values (new_workspace_id, new.id, 'owner', 'active');
  insert into public.subscriptions(workspace_id, plan_code, status, trial_starts_at, trial_ends_at) values (new_workspace_id, 'starter', 'trialing', now(), now() + interval '14 days');
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;
drop trigger if exists on_auth_user_created_trafficflow on auth.users;
create trigger on_auth_user_created_trafficflow after insert on auth.users for each row execute function private.handle_new_user();

create or replace function public.accept_workspace_invitation(p_token text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  invitation public.workspace_invitations%rowtype;
  current_email text;
begin
  if (select auth.uid()) is null then raise exception 'authentication_required' using errcode = '42501'; end if;
  current_email := lower(coalesce((select auth.jwt() ->> 'email'), ''));
  select * into invitation from public.workspace_invitations wi
   where wi.token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex')
     and lower(wi.email) = current_email
     and wi.accepted_at is null and wi.revoked_at is null and wi.expires_at > now()
   for update;
  if not found then raise exception 'invitation_invalid_or_expired' using errcode = '22023'; end if;
  insert into public.workspace_members(workspace_id,user_id,role,status,permissions)
   values (invitation.workspace_id,(select auth.uid()),invitation.role,'active',invitation.permissions)
   on conflict(workspace_id,user_id) do update set role=excluded.role,status='active',permissions=excluded.permissions;
  update public.workspace_invitations set accepted_at=now() where id=invitation.id;
  insert into public.notifications(workspace_id,user_id,kind,title,body)
   values (invitation.workspace_id,invitation.invited_by,'member_joined','Invitation acceptée',current_email || ' a rejoint le workspace.');
  return invitation.workspace_id;
end;
$$;
revoke all on function public.accept_workspace_invitation(text) from public, anon;
grant execute on function public.accept_workspace_invitation(text) to authenticated;

create or replace function public.trafficflow_create_social_account(
  p_workspace_id uuid, p_platform text, p_handle text, p_display_name text, p_niche text default 'Créateur'
) returns integer language plpgsql security definer set search_path = '' as $$
declare
  cap integer;
  current_count integer;
  new_id integer;
begin
  if not private.has_workspace_permission(p_workspace_id,'manage_social_accounts') then raise exception 'permission_denied' using errcode='42501'; end if;
  perform 1 from public.subscriptions where workspace_id=p_workspace_id for update;
  select sp.social_account_limit into cap from public.subscriptions s join public.subscription_plans sp on sp.code=s.plan_code where s.workspace_id=p_workspace_id;
  if cap is null then raise exception 'subscription_missing' using errcode='23514'; end if;
  select count(*)::integer into current_count from public.social_accounts where workspace_id=p_workspace_id;
  if current_count >= cap then raise exception 'plan_limit:social_accounts' using errcode='23514'; end if;
  insert into public.social_accounts(workspace_id,platform,handle,display_name,niche,connection_status,created_by)
    values(p_workspace_id,p_platform,p_handle,p_display_name,p_niche,'pending',(select auth.uid())) returning id into new_id;
  insert into public.ai_assistants(workspace_id,social_account_id,updated_by) values(p_workspace_id,new_id,(select auth.uid()));
  return new_id;
end;
$$;
revoke all on function public.trafficflow_create_social_account(uuid,text,text,text,text) from public, anon;
grant execute on function public.trafficflow_create_social_account(uuid,text,text,text,text) to authenticated;

create or replace function public.trafficflow_consume_ai_message(p_workspace_id uuid)
returns integer language plpgsql security definer set search_path = '' as $$
declare
  message_cap integer;
  used integer;
  month_start date := date_trunc('month', now() at time zone 'UTC')::date;
begin
  if not private.has_workspace_permission(p_workspace_id,'use_ai') then raise exception 'permission_denied' using errcode='42501'; end if;
  select sp.ai_message_limit into message_cap from public.subscriptions s join public.subscription_plans sp on sp.code=s.plan_code where s.workspace_id=p_workspace_id;
  if message_cap is null then raise exception 'subscription_missing' using errcode='23514'; end if;
  insert into public.ai_usage(workspace_id,period_start,messages_used) values(p_workspace_id,month_start,1)
  on conflict(workspace_id,period_start) do update set messages_used=public.ai_usage.messages_used+1,updated_at=now()
  where public.ai_usage.messages_used < message_cap
  returning messages_used into used;
  if used is null then raise exception 'plan_limit:ai_messages' using errcode='23514'; end if;
  return used;
end;
$$;
revoke all on function public.trafficflow_consume_ai_message(uuid) from public, anon;
grant execute on function public.trafficflow_consume_ai_message(uuid) to authenticated;

create or replace function public.trafficflow_release_ai_message(p_workspace_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare month_start date := date_trunc('month', now() at time zone 'UTC')::date;
begin
  if not private.has_workspace_permission(p_workspace_id,'use_ai') then raise exception 'permission_denied' using errcode='42501'; end if;
  update public.ai_usage set messages_used=greatest(0,messages_used-1),updated_at=now()
    where workspace_id=p_workspace_id and period_start=month_start;
end;
$$;
revoke all on function public.trafficflow_release_ai_message(uuid) from public, anon;
grant execute on function public.trafficflow_release_ai_message(uuid) to authenticated;

create or replace function public.trafficflow_create_invitation(
  p_workspace_id uuid,p_email text,p_role text,p_token_hash text,p_permissions jsonb default '{}'::jsonb
) returns uuid language plpgsql security definer set search_path = '' as $$
declare
  seat_cap integer;
  va_count integer;
  invite_id uuid;
begin
  if not private.has_workspace_role(p_workspace_id,array['owner','admin']) then raise exception 'permission_denied' using errcode='42501'; end if;
  if p_role not in ('admin','manager','va') then raise exception 'invalid_role' using errcode='22023'; end if;
  select sp.va_limit into seat_cap from public.subscriptions s join public.subscription_plans sp on sp.code=s.plan_code where s.workspace_id=p_workspace_id;
  if p_role='va' then
    select count(*)::integer into va_count from public.workspace_members wm where wm.workspace_id=p_workspace_id and wm.role='va' and wm.status in ('active','invited');
    if coalesce(va_count,0)>=coalesce(seat_cap,0) then raise exception 'plan_limit:va_members' using errcode='23514'; end if;
  end if;
  insert into public.workspace_invitations(workspace_id,email,role,token_hash,permissions,invited_by)
