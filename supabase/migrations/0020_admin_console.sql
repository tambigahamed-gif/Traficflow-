-- TrafficFlow 0020 — fondations persistantes de la console Super Admin.
-- Additif uniquement. Les écritures applicatives passent par le serveur après
-- vérification super_admin; service_role est nécessaire pour les opérations globales.

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null check (char_length(action) between 1 and 120),
  entity_type text not null check (char_length(entity_type) between 1 and 80),
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_log_created_at_idx
  on public.admin_audit_log(created_at desc);
create index if not exists admin_audit_log_actor_idx
  on public.admin_audit_log(actor_user_id, created_at desc);

create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  created_by uuid not null references auth.users(id) on delete restrict,
  requester_user_id uuid references auth.users(id) on delete set null,
  assigned_to uuid references auth.users(id) on delete set null,
  subject text not null check (char_length(subject) between 3 and 200),
  message text not null check (char_length(message) between 1 and 10000),
  status text not null default 'open' check (status in ('open', 'in_progress', 'waiting', 'resolved', 'closed')),
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists support_tickets_status_idx
  on public.support_tickets(status, priority, updated_at desc);
create index if not exists support_tickets_requester_idx
  on public.support_tickets(requester_user_id, updated_at desc);

create or replace function private.touch_support_ticket_updated_at()
returns trigger language plpgsql security definer set search_path = public, private
as $$
begin
  new.updated_at = now();
  if new.status in ('resolved', 'closed') and old.status not in ('resolved', 'closed') then
    new.resolved_at = now();
  elsif new.status not in ('resolved', 'closed') then
    new.resolved_at = null;
  end if;
  return new;
end;
$$;

drop trigger if exists support_tickets_touch_updated_at on public.support_tickets;
create trigger support_tickets_touch_updated_at
before update on public.support_tickets
for each row execute function private.touch_support_ticket_updated_at();

alter table public.admin_audit_log enable row level security;
alter table public.support_tickets enable row level security;
revoke all on public.admin_audit_log from anon;
revoke all on public.support_tickets from anon;
grant select on public.admin_audit_log to authenticated;
grant select, insert, update on public.support_tickets to authenticated;
grant all on public.admin_audit_log to service_role;
grant all on public.support_tickets to service_role;

drop policy if exists admin_audit_log_super_admin_read on public.admin_audit_log;
create policy admin_audit_log_super_admin_read on public.admin_audit_log
for select to authenticated using (private.is_super_admin());

drop policy if exists support_tickets_super_admin_read on public.support_tickets;
create policy support_tickets_super_admin_read on public.support_tickets
for select to authenticated using (private.is_super_admin());
drop policy if exists support_tickets_super_admin_insert on public.support_tickets;
create policy support_tickets_super_admin_insert on public.support_tickets
for insert to authenticated with check (private.is_super_admin() and created_by = auth.uid());
drop policy if exists support_tickets_super_admin_update on public.support_tickets;
create policy support_tickets_super_admin_update on public.support_tickets
for update to authenticated using (private.is_super_admin()) with check (private.is_super_admin());
