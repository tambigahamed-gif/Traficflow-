create or replace function public.trafficflow_revoke_invitation(p_workspace_id uuid,p_invitation_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not private.has_workspace_role(p_workspace_id,array['owner','admin']) then raise exception 'permission_denied' using errcode='42501'; end if;
  update public.workspace_invitations set revoked_at=now() where id=p_invitation_id and workspace_id=p_workspace_id and accepted_at is null and revoked_at is null;
  if not found then raise exception 'invitation_not_found_or_already_used' using errcode='P0002'; end if;
end;
$$;
revoke all on function public.trafficflow_revoke_invitation(uuid,uuid) from public,anon;
grant execute on function public.trafficflow_revoke_invitation(uuid,uuid) to authenticated;

create or replace function public.trafficflow_remove_member(p_workspace_id uuid,p_user_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not private.has_workspace_role(p_workspace_id,array['owner','admin']) then raise exception 'permission_denied' using errcode='42501'; end if;
  if exists(select 1 from public.workspaces where id=p_workspace_id and owner_id=p_user_id) then raise exception 'cannot_remove_owner' using errcode='42501'; end if;
  delete from public.workspace_members where workspace_id=p_workspace_id and user_id=p_user_id;
  if not found then raise exception 'member_not_found' using errcode='P0002'; end if;
  delete from public.account_assignments where workspace_id=p_workspace_id and user_id=p_user_id;
  update public.posts set assigned_to=null where workspace_id=p_workspace_id and assigned_to=p_user_id;
  update public.tasks set assigned_to=null where workspace_id=p_workspace_id and assigned_to=p_user_id;
end;
$$;
revoke all on function public.trafficflow_remove_member(uuid,uuid) from public,anon;
grant execute on function public.trafficflow_remove_member(uuid,uuid) to authenticated;

create or replace function public.trafficflow_create_workflow(
 p_workspace_id uuid,p_name text,p_trigger_type text,p_condition jsonb,p_action_type text,p_action_config jsonb
) returns uuid language plpgsql security definer set search_path = '' as $$
declare workflow_id uuid;
begin
  if not private.has_workspace_permission(p_workspace_id,'manage_tasks') then raise exception 'permission_denied' using errcode='42501'; end if;
  if char_length(trim(coalesce(p_name,''))) not between 1 and 120 then raise exception 'invalid_workflow_name' using errcode='22023'; end if;
  if p_trigger_type not in ('post_published','post_failed','task_done','new_comment','analytics_updated','manual') then raise exception 'invalid_trigger' using errcode='22023'; end if;
  if p_action_type not in ('notify_va','notify_manager','suggest_reply','refresh_analytics','manual') then raise exception 'invalid_action' using errcode='22023'; end if;
  insert into public.automation_workflows(workspace_id,name,trigger_type,condition,action_type,action_config,created_by)
    values(p_workspace_id,trim(p_name),p_trigger_type,coalesce(p_condition,'{}'::jsonb),p_action_type,coalesce(p_action_config,'{}'::jsonb),(select auth.uid())) returning id into workflow_id;
  return workflow_id;
end;
$$;
revoke all on function public.trafficflow_create_workflow(uuid,text,text,jsonb,text,jsonb) from public,anon;
grant execute on function public.trafficflow_create_workflow(uuid,text,text,jsonb,text,jsonb) to authenticated;

