create table if not exists public.subscription_events (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  event_type text not null check(event_type in ('trial_started','plan_change_requested','plan_changed','renewal','payment_issue','canceled','expired')),
  from_plan text references public.subscription_plans(code),
  to_plan text references public.subscription_plans(code),
  provider text,
  external_event_id text,
  note text not null default '',
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null
);
alter table public.subscription_events enable row level security;
grant select on public.subscription_events to authenticated;
create policy subscription_events_read_admin on public.subscription_events for select to authenticated using(private.has_workspace_role(workspace_id,array['owner','admin']));

create table if not exists public.plan_change_requests (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  from_plan text not null references public.subscription_plans(code),
  requested_plan text not null references public.subscription_plans(code),
  status text not null default 'awaiting_payment_provider' check(status in ('awaiting_payment_provider','submitted','fulfilled','declined','canceled')),
  requested_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  unique(workspace_id,status)
);
alter table public.plan_change_requests enable row level security;
grant select on public.plan_change_requests to authenticated;
create policy plan_change_requests_read_admin on public.plan_change_requests for select to authenticated using(private.has_workspace_role(workspace_id,array['owner','admin']));

create or replace function public.trafficflow_request_plan_change(p_workspace_id uuid,p_plan_code text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare current_plan text; request_id uuid;
begin
  if not private.has_workspace_role(p_workspace_id,array['owner','admin']) then raise exception 'permission_denied' using errcode='42501'; end if;
  if p_plan_code not in ('starter','pro','business','enterprise') then raise exception 'invalid_plan' using errcode='22023'; end if;
  select plan_code into current_plan from public.subscriptions where workspace_id=p_workspace_id for update;
  if current_plan is null then raise exception 'subscription_missing' using errcode='23514'; end if;
  if current_plan=p_plan_code then raise exception 'plan_already_active' using errcode='22023'; end if;
  insert into public.plan_change_requests(workspace_id,from_plan,requested_plan,requested_by)
    values(p_workspace_id,current_plan,p_plan_code,(select auth.uid()))
    on conflict(workspace_id,status) do update set from_plan=excluded.from_plan,requested_plan=excluded.requested_plan,requested_by=excluded.requested_by,created_at=now()
    returning id into request_id;
  insert into public.subscription_events(workspace_id,event_type,from_plan,to_plan,note,created_by)
    values(p_workspace_id,'plan_change_requested',current_plan,p_plan_code,'Paiement non configuré ; demande en attente, abonnement inchangé.',(select auth.uid()));
  insert into public.notifications(workspace_id,user_id,kind,title,body)
    values(p_workspace_id,(select auth.uid()),'system','Demande de changement enregistrée','Aucun paiement n’a été débité ; le plan actuel reste actif.');
  return request_id;
end;
$$;
revoke all on function public.trafficflow_request_plan_change(uuid,text) from public,anon;
grant execute on function public.trafficflow_request_plan_change(uuid,text) to authenticated;

